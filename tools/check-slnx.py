"""Verify LiveArchiveEncoder.V7.slnx Solution Items match the working tree.

The .slnx manifest is what the IDE shows; it drifts silently whenever a file is
added without opening the solution. This check fails on BOTH directions:
  * a listed path that no longer exists,
  * a source / test / tool / doc file that is not listed.

Run it locally or let CI run it; it needs only the standard library.
"""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SLNX = ROOT / "LiveArchiveEncoder.V7.slnx"

EXCLUDE_DIRS = {
    ".git", "bin", "obj", "publish", "TestResults", ".pytest_cache",
    ".venv", "__pycache__", "out", ".codebuddy",
}
EXTENSIONS = {
    ".cs", ".py", ".md", ".yml", ".yaml", ".ps1", ".sh", ".json",
    ".props", ".config", ".ini", ".slnx", ".txt", ".service", ".xml",
}
SPECIAL_NAMES = {
    "LICENSE", ".gitignore", ".gitattributes", "nuget.config", "pytest.ini",
    "Directory.Build.props", "global.json", ".woodpecker.yaml",
    "requirements.txt", "forgejo-runner.service",
}

text = SLNX.read_text(encoding="utf-8")
listed = set(re.findall(r'<File Path="([^"]+)"', text))
projects = set(re.findall(r'<Project Path="([^"]+)"', text))

expected: set[str] = set()
for path in ROOT.rglob("*"):
    if not path.is_file():
        continue
    rel = path.relative_to(ROOT).as_posix()
    parts = rel.split("/")
    if any(part in EXCLUDE_DIRS for part in parts[:-1]):
        continue
    if path.suffix.lower() not in EXTENSIONS and path.name not in SPECIAL_NAMES:
        continue
    if rel.endswith(".csproj"):
        continue
    expected.add(rel)

missing = sorted(p for p in listed | projects if not (ROOT / p).is_file())
unlisted = sorted(expected - listed)
# Files generated by this check's own run (HTML test reports etc.) are excluded
# above; anything left is a genuine manifest gap.

print(f".slnx: {len(listed)} files, {len(projects)} projects; "
      f"tree: {len(expected)} candidate files")
for path in missing:
    print(f"  STALE   {path}")
for path in unlisted:
    print(f"  MISSING {path}")

if missing or unlisted:
    print(f"\nmanifest drift: {len(missing)} stale, {len(unlisted)} unlisted. "
          "Regenerate the Solution Items from the tree.", file=sys.stderr)
    sys.exit(1)

# v7.9.9.4: every document ships in both languages. A half-translated pair is a
# documentation bug that nothing else catches, so check it here.
#
#   docs/*.md  <->  docs/*.en.md      (X.md is Chinese, X.en.md is English)
#   archive/README.md <-> archive/README.en.md
#   README.md <-> README.zh.md        the one exception: the root README keeps
#                                     English as its main text and links to a
#                                     Chinese edition, because it is the repo's
#                                     landing page.
unpaired: list[str] = []
for path in sorted((ROOT / "docs").glob("*.md")):
    if path.stem.endswith(".en"):
        twin = path.with_name(path.stem[:-3] + ".md")
    else:
        twin = path.with_name(path.stem + ".en.md")
    if not twin.is_file():
        unpaired.append(f"{path.relative_to(ROOT)} <-> {twin.relative_to(ROOT)}")

for name, twin_name in (("archive/README.md", "archive/README.en.md"),
                        ("archive/README.en.md", "archive/README.md"),
                        ("README.md", "README.zh.md"),
                        ("README.zh.md", "README.md")):
    if not (ROOT / twin_name).is_file():
        unpaired.append(f"{name} <-> {twin_name}")

if unpaired:
    for pair in unpaired:
        print(f"  UNPAIRED {pair}")
    print(f"\nlanguage drift: {len(unpaired)} document(s) without a both-language "
          "twin. Add the missing edition.", file=sys.stderr)
    sys.exit(1)
print("manifest OK, language pairs OK")
