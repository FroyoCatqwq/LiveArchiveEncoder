using System.Text;
using LiveArchiveEncoder.Core;

namespace LiveArchiveEncoder.PostProcess;

/// <summary>
/// Turns a user-supplied FFmpeg argument fragment into an argument vector, and
/// rejects the parts that would hijack the input or the output.
///
/// The post-processing stages let the user write the middle of an FFmpeg command
/// -- <c>-vf "yadif,fps=15" -c:v libx264 -crf 28</c> -- while the program owns
/// the two ends: <c>ffmpeg -y -i &lt;live product&gt; ... &lt;output&gt;</c>.
/// Handing over the ends as well would let a typo overwrite the source, so the
/// fragment is tokenised here (rather than passed through a shell) and checked
/// token by token.
/// </summary>
public static class PostArgs
{
    /// <summary>
    /// Split on whitespace, honouring single and double quotes.
    ///
    /// Backslashes are deliberately <em>not</em> escapes: Windows paths inside
    /// ffmpeg arguments (<c>-vf "drawtext=fontfile=C:\Windows\Fonts\a.ttf"</c>)
    /// rely on them being literal, and eating them would break the common case
    /// to serve a rare one.
    /// </summary>
    public static List<string> Tokenize(string? fragment)
    {
        var tokens = new List<string>();
        if (!fragment.HasText) return tokens;

        var current = new StringBuilder();
        char? quote = null;
        bool any = false;

        void Flush()
        {
            if (any) tokens.Add(current.ToString());
            current.Clear();
            any = false;
        }

        foreach (char c in fragment)
        {
            if (quote is not null)
            {
                if (c == quote.Value) { quote = null; any = true; continue; }
                current.Append(c);
                any = true;
                continue;
            }

            if (c == '"' || c == '\'') { quote = c; any = true; continue; }

            if (char.IsWhiteSpace(c)) { Flush(); continue; }

            current.Append(c);
            any = true;
        }

        // An unterminated quote is a typo, not a reason to silently drop the
        // tail: keep what was parsed and let validation report the oddity.
        Flush();
        return tokens;
    }

    /// <summary>
    /// Reject the fragments this pipeline must not accept:
    /// <list type="bullet">
    /// <item><description>an empty fragment -- there is nothing to run;</description></item>
    /// <item><description><c>-i</c>, which would add a second input;</description></item>
    /// <item><description><c>-o</c>, which is not an FFmpeg output flag anyway;</description></item>
    /// <item><description>a trailing bare token that looks like a path, which
    /// FFmpeg would treat as an extra output.</description></item>
    /// </list>
    /// Everything else -- including <c>-filter_complex</c>, multiple <c>-map</c>
    /// and <c>-ss</c> -- is the user's business.
    /// </summary>
    public static (bool Ok, string? Error) Validate(IReadOnlyList<string> tokens)
    {
        if (tokens.Count == 0)
            return (false, "the argument fragment is empty; there is nothing to run");

        // v7.9.9.3: check EVERY position, not just the tail. FFmpeg treats any
        // free-standing non-option token as another output file, so a bare
        // "evil.mp4" in the middle used to slip through and could overwrite an
        // unrelated path while the intended output became the second one.
        bool expectValue = false;
        foreach (string token in tokens)
        {
            if (token is "-i")
                return (false, "'-i' is not allowed here: the input is the live recording and is chosen by the program");
            if (token is "-o")
                return (false, "'-o' is not an FFmpeg flag; drop it and name no output");

            if (token.StartsWith('-'))
            {
                expectValue = !ValueLessFlags.Contains(token);
                continue;
            }
            if (expectValue) { expectValue = false; continue; }   // an option's value

            return (false, $"'{token}' looks like an output file name (an extra output); "
                + "the output path is generated by the program");
        }

        return (true, null);
    }

    /// <summary>Output-side switches that take no value.</summary>
    private static readonly HashSet<string> ValueLessFlags =
        new(StringComparer.Ordinal)
        {
            "-y", "-n", "-an", "-vn", "-sn", "-dn", "-shortest", "-copyts",
            "-start_at_zero", "-nostdin", "-hide_banner", "-noautorotate",
            "-ignore_unknown", "-copy_unknown", "-re", "-benchmark",
        };

    public static (List<string> Tokens, string? Error) Parse(string? fragment)
    {
        List<string> tokens = Tokenize(fragment);
        (bool ok, string? error) = Validate(tokens);
        return ok ? (tokens, null) : (tokens, error);
    }

    /// <summary>
    /// Escape a value for use inside a single-quoted drawtext/filter expression.
    /// FFmpeg's filter parser treats <c>\</c>, <c>:</c> and <c>'</c> specially
    /// even inside quotes, so each has to be backslashed.
    /// </summary>
    public static string EscapeFilterValue(string? value)
    {
        if (string.IsNullOrEmpty(value)) return "";

        var sb = new StringBuilder(value.Length);
        foreach (char c in value)
        {
            switch (c)
            {
                case '\\': sb.Append("\\\\"); break;
                case ':': sb.Append("\\:"); break;
                case '\'': sb.Append("\\'"); break;
                case '[': sb.Append("\\["); break;
                case ']': sb.Append("\\]"); break;
                case ',': sb.Append("\\,"); break;
                case ';': sb.Append("\\;"); break;
                default: sb.Append(c); break;
            }
        }
        return sb.ToString();
    }
}
