using System.Text;

namespace Lae.Core;

/// <summary>
/// Turns a user-written FFmpeg argument fragment into an argument vector, and
/// refuses the parts that would take over the two ends of the command.
///
/// <para>The post-encode passes let the user write the middle of an FFmpeg
/// command -- <c>-c:v libx264 -crf 30</c> -- while the program owns
/// <c>-i &lt;previous product&gt;</c> and the output path. Handing over the ends
/// as well would let a typo overwrite the recording that took twenty minutes to
/// capture, so the fragment is split here rather than passed to a shell, and
/// every token is checked.</para>
///
/// <para>Splitting rather than shelling out is also what keeps a fragment with
/// <c>&amp;&amp;</c> or <c>|</c> in it from doing something. It is not a filter
/// against a hostile user -- it is the same user -- it is a filter against the
/// kind of typo that turns a re-encode into a deletion.</para>
/// </summary>
public static class ArgsFragment
{
    /// <summary>
    /// Split on whitespace, honouring single and double quotes.
    ///
    /// <para>Backslashes are deliberately <em>not</em> escapes: a Windows path
    /// inside a filter expression (<c>drawtext=fontfile=C:\Fonts\a.ttf</c>)
    /// relies on them being literal, and eating them would break the common case
    /// to serve a rare one.</para>
    /// </summary>
    public static List<string> Tokenize(string? fragment)
    {
        var tokens = new List<string>();
        if (!fragment.HasText) return tokens;

        var current = new StringBuilder();
        char? quote = null;
        bool any = false;

        void Flush()
        {
            if (any) tokens.Add(current.ToString());
            current.Clear();
            any = false;
        }

        foreach (char c in fragment)
        {
            if (quote is not null)
            {
                if (c == quote.Value) { quote = null; any = true; continue; }
                current.Append(c);
                any = true;
                continue;
            }

            if (c is '"' or '\'') { quote = c; any = true; continue; }
            if (char.IsWhiteSpace(c)) { Flush(); continue; }

            current.Append(c);
            any = true;
        }

        // An unterminated quote is a typo, not a reason to drop the tail: keep
        // what was parsed and let the caller see what it is about to run.
        Flush();
        return tokens;
    }

    /// <summary>
    /// The reasons these tokens must not be run, or null. Covers the four ways a
    /// fragment can take over the command:
    /// <list type="bullet">
    /// <item><description>it is empty -- there is nothing to run;</description></item>
    /// <item><description><c>-i</c>, which would add a second input;</description></item>
    /// <item><description><c>-o</c>, which is not an FFmpeg flag at all;</description></item>
    /// <item><description>a trailing bare token that reads as a path, which
    /// FFmpeg would treat as a second output.</description></item>
    /// </list>
    /// Everything else -- <c>-filter_complex</c>, several <c>-map</c>,
    /// <c>-ss</c> -- is the user's business.
    /// </summary>
    public static string? Validate(IReadOnlyList<string> tokens)
    {
        if (tokens.Count == 0) return "the argument fragment is empty; there is nothing to run";

        foreach (string token in tokens)
        {
            if (token is "-i")
                return "'-i' is not allowed here: the input is the product of the previous pass";
            if (token is "-o")
                return "'-o' is not an FFmpeg flag; drop it and name no output";
        }

        // A trailing token that is not an option is where a stray output name
        // would sit. Option values elsewhere are fine -- that is what
        // "-crf 30" and "-c:v libx264" look like -- so only the last position is
        // suspicious, and only when it really reads as a path.
        string last = tokens[^1];
        if (!last.StartsWith('-') && LooksLikePath(last))
            return $"'{last}' looks like an output name; the output path is generated by the program";

        return null;
    }

    /// <summary>Tokens plus the reason they cannot be used, if any.</summary>
    public static (List<string> Tokens, string? Error) Parse(string? fragment)
    {
        List<string> tokens = Tokenize(fragment);
        return (tokens, Validate(tokens));
    }

    /// <summary>
    /// Conservative: a separator, or an extension from the short list of
    /// containers people actually produce. A bare word such as <c>libx264</c> or
    /// <c>yadif</c> must not trip it.
    /// </summary>
    private static bool LooksLikePath(string token)
    {
        if (token.Contains('/') || token.Contains('\\')) return true;

        int dot = token.LastIndexOf('.');
        if (dot <= 0 || dot == token.Length - 1) return false;

        return token[(dot + 1)..].ToLowerInvariant() switch
        {
            "mp4" or "mkv" or "avi" or "mov" or "webm" or "flv" or "wmv"
                or "mpg" or "mpeg" or "ts" or "m4v" or "rm" or "rmvb"
                or "asf" or "ogv" or "3gp" or "gif" => true,
            _ => false,
        };
    }
}
